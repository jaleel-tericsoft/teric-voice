import { Document, Page, View, Text, StyleSheet } from "@react-pdf/renderer";
import { formatAnswerValue } from "@/lib/form-utils";
import type { Entry, FormDefinition, Organization } from "@/types";

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 10, fontFamily: "Helvetica", color: "#17212B" },
  headerRow: {
    flexDirection: "row",
    justifyContent: "space-between",
    alignItems: "flex-start",
    marginBottom: 20,
    paddingBottom: 16,
    borderBottomWidth: 1,
    borderBottomColor: "#D9DEDF",
    borderBottomStyle: "solid",
  },
  brandRow: { flexDirection: "row", alignItems: "center" },
  logoMark: {
    width: 36,
    height: 36,
    borderRadius: 8,
    backgroundColor: "#102A43",
    alignItems: "center",
    justifyContent: "center",
    marginRight: 10,
  },
  logoText: { color: "#FFFFFF", fontSize: 13, fontWeight: 700 },
  orgName: { fontSize: 10, fontWeight: 700, color: "#52606D" },
  formTitle: { fontSize: 16, fontWeight: 700, color: "#102A43", marginTop: 2 },
  metaBlock: { alignItems: "flex-end" },
  metaLine: { fontSize: 9, color: "#52606D", marginBottom: 2 },
  statusPill: {
    marginTop: 2,
    paddingVertical: 3,
    paddingHorizontal: 8,
    borderRadius: 10,
    backgroundColor: "#EAF0F2",
  },
  statusPillText: { fontSize: 8, fontWeight: 700, color: "#102A43" },
  sectionTitle: {
    fontSize: 10,
    fontWeight: 700,
    color: "#1F5A63",
    marginTop: 16,
    marginBottom: 8,
    textTransform: "uppercase",
    letterSpacing: 0.6,
  },
  grid: { flexDirection: "row", flexWrap: "wrap" },
  qaRow: { width: "50%", marginBottom: 10, paddingRight: 12 },
  question: { fontSize: 8.5, color: "#52606D", marginBottom: 2 },
  answer: { fontSize: 10.5, color: "#17212B", fontWeight: 500 },
  footer: {
    position: "absolute",
    bottom: 24,
    left: 40,
    right: 40,
    flexDirection: "row",
    justifyContent: "space-between",
    alignItems: "center",
    paddingTop: 8,
    borderTopWidth: 1,
    borderTopColor: "#D9DEDF",
    borderTopStyle: "solid",
  },
  footerText: { fontSize: 7.5, color: "#7B8794" },
});

function initials(name: string) {
  return name
    .split(" ")
    .map((p) => p[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
}

export function EntryPdfDocument({
  entry,
  form,
  organization,
}: {
  entry: Entry;
  form: FormDefinition;
  organization: Organization;
}) {
  const version =
    form.versions.find((v) => v.version === entry.formVersion) ??
    form.versions[form.versions.length - 1];
  const generatedAt = new Date();

  return (
    <Document title={`${form.name} — ${entry.id}`}>
      <Page size="A4" style={styles.page}>
        <View style={styles.headerRow}>
          <View style={styles.brandRow}>
            <View style={styles.logoMark}>
              <Text style={styles.logoText}>{initials(organization.name)}</Text>
            </View>
            <View>
              <Text style={styles.orgName}>{organization.name.toUpperCase()}</Text>
              <Text style={styles.formTitle}>{form.name}</Text>
            </View>
          </View>
          <View style={styles.metaBlock}>
            <Text style={styles.metaLine}>Entry ID: {entry.id}</Text>
            <Text style={styles.metaLine}>Form Version: v{entry.formVersion}</Text>
            <Text style={styles.metaLine}>
              Submitted: {new Date(entry.submittedAt ?? entry.createdAt).toLocaleDateString("en-IN", {
                day: "2-digit",
                month: "short",
                year: "numeric",
              })}
            </Text>
            <View style={styles.statusPill}>
              <Text style={styles.statusPillText}>{entry.status.replace(/_/g, " ").toUpperCase()}</Text>
            </View>
          </View>
        </View>

        {version?.sections.map((section) => {
          const visible = section.questions.filter((q) =>
            entry.answers.some((a) => a.fieldName === q.fieldName)
          );
          if (!visible.length) return null;
          return (
            <View key={section.id} wrap={false}>
              <Text style={styles.sectionTitle}>{section.title}</Text>
              <View style={styles.grid}>
                {visible.map((q) => {
                  const answer = entry.answers.find((a) => a.fieldName === q.fieldName)!;
                  return (
                    <View key={q.id} style={styles.qaRow}>
                      <Text style={styles.question}>{q.questionText}</Text>
                      <Text style={styles.answer}>{formatAnswerValue(form, answer)}</Text>
                    </View>
                  );
                })}
              </View>
            </View>
          );
        })}

        <View style={styles.footer} fixed>
          <Text style={styles.footerText}>Generated by {organization.name} · TericVoice</Text>
          <Text
            style={styles.footerText}
            render={({ pageNumber, totalPages }) =>
              `Page ${pageNumber} of ${totalPages} · ${generatedAt.toLocaleString("en-IN", {
                day: "2-digit",
                month: "short",
                year: "numeric",
                hour: "2-digit",
                minute: "2-digit",
              })}`
            }
          />
        </View>
      </Page>
    </Document>
  );
}
